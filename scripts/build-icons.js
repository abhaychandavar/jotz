// Generates src/icons.js from lucide-static. Edit the map below to add or swap icons.
const fs = require('fs');
const path = require('path');

const MAP = {
  back: 'chevron-left',
  fwd: 'chevron-right',
  chev: 'chevron-down',
  archive: 'archive',
  unarchive: 'archive-restore',
  trash: 'trash-2',
  full: 'maximize',
  gear: 'settings',
  plus: 'plus',
  sun: 'sun',
  moon: 'moon',
  monitor: 'monitor',
  calendar: 'calendar',
  checkCircle: 'circle-check',
  todo: 'square-check',
  list: 'list',
  listOrdered: 'list-ordered',
  text: 'type',
  more: 'ellipsis',
  grip: 'grip-vertical',
  note: 'file-text',
  sort: 'arrow-up-down',
  flag: 'flag',
  keyboard: 'keyboard',
  game: 'gamepad-2',
  bold: 'bold',
  italic: 'italic',
  underline: 'underline',
  highlight: 'highlighter',
  color: 'baseline',
  size: 'a-large-small',
  side: 'panel-left',
  clear: 'remove-formatting',
  heading: 'heading',
  palette: 'palette',
  open: 'external-link',
  check: 'check',
  star: 'star',
};

const dir = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');
const inner = (name) =>
  fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<svg[\s\S]*?>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/ \/>/g, '/>');

const body = Object.entries(MAP)
  .map(([key, name]) => `  ${key}: '${inner(name)}',`)
  .join('\n');
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'icons.js'),
  `// Generated by scripts/build-icons.js from lucide-static. Do not edit.\nconst ICONS = {\n${body}\n};\n`
);
